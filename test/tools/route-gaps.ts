/**
 * Which Canvas API endpoints does the node not reach?
 *
 * Compares the route table of a real Canvas (test/fixtures/canvas-routes.json,
 * where each route is marked documented or not) with the requests every
 * operation of the node builds, and writes test/ROUTE_GAPS.md.
 *
 * An "endpoint" is a controller action; Canvas often exposes one under several
 * paths (per course, group, user ...). It counts as covered when the node
 * reaches at least one of them.
 *
 * Usage: npx tsx test/tools/route-gaps.ts
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { buildRequestFor, listOperations, paramVariants } from '../lib/catalog';
import { canvasRoutes } from '../lib/routes';

interface FixtureRoute {
	verb: string;
	path: string;
	to: string;
	documented?: boolean;
}

const fixture = JSON.parse(
	readFileSync(resolve(__dirname, '..', 'fixtures', 'canvas-routes.json'), 'utf8'),
) as { source: string; routes: FixtureRoute[] };

// --- Which routes do the node's operations reach? (most specific match wins) ---
const literalSegments = (path: string): number =>
	path.split('/').filter((segment) => segment && !segment.startsWith(':') && !segment.startsWith('*')).length;

const reached = new Set<string>();
for (const op of listOperations()) {
	if (op.resource === 'apiRequest') continue; // free-form: reaches whatever the user types
	for (const variant of paramVariants(op)) {
		try {
			const request = buildRequestFor(op.resource, op.operation, variant.params);
			const path = request.endpoint.split('?')[0];
			const matches = canvasRoutes().filter(
				(route) => route.verb === request.method.toUpperCase() && route.pattern.test(path),
			);
			if (matches.length === 0) continue;
			const best = Math.max(...matches.map((match) => literalSegments(match.path)));
			for (const match of matches) {
				if (literalSegments(match.path) === best) reached.add(`${match.verb} ${match.path}`);
			}
		} catch {
			// minimal variants of operations that need at least one entry
		}
	}
}

// --- Group the route table by endpoint (controller#action) ---
interface Endpoint {
	controller: string;
	action: string;
	documented: boolean;
	routes: string[];
	covered: number;
}
const endpoints = new Map<string, Endpoint>();
for (const route of fixture.routes) {
	if (!route.path.startsWith('/api/v1')) continue;
	const [controller, action] = route.to.split('#');
	const endpoint = endpoints.get(route.to) ?? {
		controller,
		action,
		documented: route.documented === true,
		routes: [],
		covered: 0,
	};
	const key = `${route.verb} ${route.path}`;
	endpoint.routes.push(key);
	if (reached.has(key)) endpoint.covered++;
	endpoints.set(route.to, endpoint);
}

const all = [...endpoints.values()];
const documented = all.filter((e) => e.documented);
const undocumented = all.filter((e) => !e.documented);
const missing = (list: Endpoint[]): Endpoint[] => list.filter((e) => e.covered === 0);
const partial = documented.filter((e) => e.covered > 0 && e.covered < e.routes.length);

function section(title: string, list: Endpoint[], note: string): string[] {
	const byController = new Map<string, Endpoint[]>();
	for (const endpoint of list) {
		byController.set(endpoint.controller, [...(byController.get(endpoint.controller) ?? []), endpoint]);
	}
	const lines = [`## ${title}`, '', note, ''];
	for (const [controller, group] of [...byController].sort((a, b) => b[1].length - a[1].length || a[0].localeCompare(b[0]))) {
		lines.push(`### ${controller} (${group.length})`, '');
		for (const endpoint of group.sort((a, b) => a.action.localeCompare(b.action))) {
			const shown = endpoint.routes.slice(0, 3).map((r) => `\`${r.replace('/api/v1', '')}\``);
			const more = endpoint.routes.length > 3 ? ` (+${endpoint.routes.length - 3} more)` : '';
			lines.push(`- **${endpoint.action}**: ${shown.join(', ')}${more}`);
		}
		lines.push('');
	}
	return lines;
}

const lines = [
	'# Canvas API endpoints the node does not reach',
	'',
	'Generated by `npx tsx test/tools/route-gaps.ts` from the route table of ' + fixture.source + '.',
	'Only `/api/v1` is listed; `/api/lti` needs LTI tokens and New Quizzes and Analytics are separate services.',
	'Everything here can still be called through the **Custom API Request** resource.',
	'',
	'| | Endpoints | Reached by an operation | Not reached |',
	'|---|---:|---:|---:|',
	`| Documented by Instructure | ${documented.length} | ${documented.length - missing(documented).length} | ${missing(documented).length} |`,
	`| Not documented | ${undocumented.length} | ${undocumented.length - missing(undocumented).length} | ${missing(undocumented).length} |`,
	'',
	`${partial.length} documented endpoints are reached for some of their contexts only (listed at the end).`,
	'',
	...section(
		'Documented endpoints without an operation',
		missing(documented),
		'Published in Instructure\'s API documentation. Some belong to hosted or feature-gated services that an open-source Canvas cannot exercise.',
	),
	...section(
		'Undocumented endpoints without an operation',
		missing(undocumented),
		'Used by the Canvas web interface or internal tooling. They accept an API token but Instructure may change them without notice.',
	),
	'## Documented endpoints reached for some contexts only',
	'',
	...partial
		.sort((a, b) => a.controller.localeCompare(b.controller))
		.map(
			(e) =>
				`- **${e.controller}#${e.action}**: not reached: ${e.routes
					.filter((r) => !reached.has(r))
					.map((r) => `\`${r.replace('/api/v1', '')}\``)
					.join(', ')}`,
		),
	'',
];

writeFileSync(resolve(__dirname, '..', 'ROUTE_GAPS.md'), lines.join('\n'));
console.log(
	`documented: ${documented.length - missing(documented).length}/${documented.length} reached; ` +
		`undocumented: ${undocumented.length - missing(undocumented).length}/${undocumented.length} reached; ` +
		`${partial.length} partial`,
);
