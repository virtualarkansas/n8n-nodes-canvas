/**
 * Build test/COVERAGE.md from the execution log the integration battery writes
 * (test/.results/ops.jsonl): for every operation the node offers, did the
 * battery execute it against Canvas, and how did it end?
 *
 * Usage: npx tsx test/tools/coverage.ts [--check] [--merge <other ops.jsonl> ...]
 *   --check   exit 1 when an operation was neither executed successfully nor skipped with a reason
 */
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { buildRequestFor, listOperations, paramVariants } from '../lib/catalog';
import { findRoute } from '../lib/routes';

interface OpRecord {
	resource: string;
	operation: string;
	outcome: 'success' | 'error-output' | 'failed' | 'debug' | 'skipped';
	reason?: string;
}

const args = process.argv.slice(2);
const check = args.includes('--check');
const logs = [resolve(__dirname, '..', '.results', 'ops.jsonl')];
for (let i = 0; i < args.length; i++) {
	if (args[i] === '--merge' && args[i + 1]) logs.push(resolve(args[++i]));
}

const records: OpRecord[] = [];
for (const file of logs) {
	if (!existsSync(file)) continue;
	for (const line of readFileSync(file, 'utf8').split('\n')) {
		if (line.trim()) records.push(JSON.parse(line) as OpRecord);
	}
}

interface Row {
	resource: string;
	operation: string;
	success: number;
	errors: number;
	failed: number;
	skipped?: string;
	route: boolean;
}

/** Operations whose path is whatever the user enters: there is no route to audit. */
const FREE_FORM = new Set(['apiRequest.request']);
const freeForm = (row: { resource: string; operation: string }): boolean => FREE_FORM.has(`${row.resource}.${row.operation}`);

const rows: Row[] = listOperations().map((op) => {
	const mine = records.filter((r) => r.resource === op.resource && r.operation === op.operation);
	let route = true;
	for (const variant of freeForm(op) ? [] : paramVariants(op)) {
		try {
			const request = buildRequestFor(op.resource, op.operation, variant.params);
			if (!findRoute(request.method, request.endpoint.split('?')[0])) route = false;
		} catch {
			// minimal variants of "at least one entry" operations
		}
	}
	return {
		resource: op.resource,
		operation: op.operation,
		success: mine.filter((r) => r.outcome === 'success').length,
		errors: mine.filter((r) => r.outcome === 'error-output').length,
		failed: mine.filter((r) => r.outcome === 'failed').length,
		skipped: mine.find((r) => r.outcome === 'skipped')?.reason,
		route,
	};
});

const status = (row: Row): string => {
	if (row.success > 0) return 'passed';
	if (row.skipped) return 'skipped';
	if (row.errors > 0 || row.failed > 0) return 'errors only';
	return 'not run';
};

const count = (wanted: string): number => rows.filter((r) => status(r) === wanted).length;
const lines: string[] = [
	'# Operation coverage',
	'',
	'Generated by `npx tsx test/tools/coverage.ts` from the integration battery\'s execution log.',
	'',
	`- Operations offered by the node: **${rows.length}**`,
	`- Executed successfully against Canvas: **${count('passed')}**`,
	`- Skipped with a stated reason: **${count('skipped')}**`,
	`- Only ever produced errors: **${count('errors only')}**`,
	`- Never run: **${count('not run')}**`,
	`- Failing the route audit: **${rows.filter((r) => !r.route).length}**`,
	'',
	'"Runs" counts successful executions; "Error runs" counts executions that ended on the Error output or failed (error-path tests land here).',
	'',
];

const byResource = new Map<string, Row[]>();
for (const row of rows) byResource.set(row.resource, [...(byResource.get(row.resource) ?? []), row]);

for (const [resource, list] of [...byResource].sort(([a], [b]) => a.localeCompare(b))) {
	lines.push(`## ${resource}`, '', '| Operation | Status | Runs | Error runs | Route | Note |', '|---|---|---:|---:|---|---|');
	for (const row of list.sort((a, b) => a.operation.localeCompare(b.operation))) {
		lines.push(
			`| ${row.operation} | ${status(row)} | ${row.success} | ${row.errors + row.failed} | ${freeForm(row) ? 'any path' : row.route ? 'ok' : 'MISSING'} | ${row.skipped ?? ''} |`,
		);
	}
	lines.push('');
}

writeFileSync(resolve(__dirname, '..', 'COVERAGE.md'), lines.join('\n'));
console.log(
	`passed ${count('passed')}, skipped ${count('skipped')}, errors only ${count('errors only')}, not run ${count('not run')}, of ${rows.length}`,
);

if (check) {
	const bad = rows.filter((r) => status(r) === 'not run' || status(r) === 'errors only' || !r.route);
	if (bad.length > 0) {
		console.error(`Uncovered operations:\n${bad.map((r) => `  ${r.resource}.${r.operation} (${status(r)}${r.route ? '' : ', no route'})`).join('\n')}`);
		process.exit(1);
	}
}
