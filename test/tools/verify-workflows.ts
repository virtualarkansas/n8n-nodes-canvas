/**
 * Import every generated example workflow (test/workflows/*.json) into the
 * battery's n8n instance, run it once and report, per workflow, how many of
 * its Canvas steps ran and how many ended without an error.
 *
 * The workflows are tours, not assertions: a step can legitimately fail when
 * it depends on a record the battery created outside the workflow. The point
 * is that the files import, execute end to end and mostly succeed.
 *
 * Usage: npx tsx test/tools/verify-workflows.ts [resource ...]
 */
import { randomUUID } from 'node:crypto';
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { CANVAS_NODE_TYPE, N8nClient } from '../lib/n8n';
import type { Json, N8nNode, N8nWorkflow } from '../lib/n8n';
import { loadState } from '../lib/state';

const dir = resolve(__dirname, '..', 'workflows');
const only = process.argv.slice(2);
const state = loadState();
const admin = state.n8n.credentials.admin;
const api = new N8nClient();

interface Outcome {
	resource: string;
	steps: number;
	executed: number;
	succeeded: number;
	status: string;
	failedSteps: string[];
}

async function run(file: string): Promise<Outcome> {
	const resource = file.replace(/\.json$/, '');
	const workflow = JSON.parse(readFileSync(resolve(dir, file), 'utf8')) as N8nWorkflow;
	const path = `verify-${randomUUID()}`;

	const nodes = workflow.nodes.map((node): N8nNode => {
		if (node.type === 'n8n-nodes-base.manualTrigger') {
			// Same name, so the connections still apply; a webhook lets the tool start the run.
			return {
				...node,
				type: 'n8n-nodes-base.webhook',
				typeVersion: 2,
				webhookId: path,
				parameters: { httpMethod: 'POST', path, responseMode: 'lastNode', options: {} },
			};
		}
		if (node.type === CANVAS_NODE_TYPE) {
			return { ...node, credentials: { [admin.type]: { id: admin.id, name: admin.name } } };
		}
		return node;
	});
	const steps = nodes.filter((node) => node.type === CANVAS_NODE_TYPE);

	const id = await api.createWorkflow({
		name: `[verify] ${workflow.name}`,
		nodes,
		connections: workflow.connections,
		settings: workflow.settings,
	});
	try {
		await api.activate(id);
		await api.callWebhook(path, {}, { timeoutMs: 1_800_000 });
		const execution = await api.lastExecution(id, 400);
		let executed = 0;
		let succeeded = 0;
		const failedSteps: string[] = [];
		for (const step of steps) {
			const runData = execution.nodes[step.name]?.[0];
			if (!runData) continue;
			executed++;
			const errors = runData.outputs[1]?.length ?? 0;
			if (!runData.error && errors === 0) {
				succeeded++;
			} else {
				const first = (runData.outputs[1]?.[0] ?? runData.error ?? {}) as Json;
				failedSteps.push(`${step.name}: ${String(first.errorCode ?? '')} ${String(first.errorMessage ?? first.message ?? '').slice(0, 120)}`);
			}
		}
		return { resource, steps: steps.length, executed, succeeded, status: execution.status, failedSteps };
	} finally {
		await api.deleteWorkflow(id).catch(() => undefined);
	}
}

async function main(): Promise<void> {
	const files = readdirSync(dir)
		.filter((file) => file.endsWith('.json'))
		.filter((file) => only.length === 0 || only.includes(file.replace(/\.json$/, '')))
		.sort();
	const outcomes: Outcome[] = [];
	for (const file of files) {
		try {
			const outcome = await run(file);
			outcomes.push(outcome);
			console.log(`${outcome.resource}: ${outcome.status}, ${outcome.succeeded}/${outcome.steps} steps succeeded (${outcome.executed} executed)`);
			for (const failed of outcome.failedSteps) console.log(`    - ${failed}`);
		} catch (error) {
			console.log(`${file}: could not be run: ${(error as Error).message.slice(0, 300)}`);
			outcomes.push({ resource: file.replace(/\.json$/, ''), steps: 0, executed: 0, succeeded: 0, status: 'not run', failedSteps: [] });
		}
	}

	const total = outcomes.reduce((n, o) => n + o.steps, 0);
	const executed = outcomes.reduce((n, o) => n + o.executed, 0);
	const succeeded = outcomes.reduce((n, o) => n + o.succeeded, 0);
	const lines = [
		'# Example workflows',
		'',
		'One workflow per resource, generated by `npx tsx test/tools/export-workflows.ts` from the operations the',
		'integration battery executed successfully. Import a file into n8n, choose your Canvas credential on the',
		'Canvas nodes and fill in the **Config** node with IDs from your own Canvas (use a sandbox, not production:',
		'the workflows create, change and delete records).',
		'',
		'Each step continues on error, so one failing step does not stop the tour. Steps can fail where they',
		'refer to a record the battery prepared outside the workflow.',
		'',
		`Last verification (\`npx tsx test/tools/verify-workflows.ts\`): ${outcomes.length} workflows imported and run on n8n; ` +
			`${executed} of ${total} steps executed, ${succeeded} without an error.`,
		'',
		'| Workflow | Run | Steps | Executed | Succeeded |',
		'|---|---|---:|---:|---:|',
		...outcomes.map((o) => `| ${o.resource} | ${o.status} | ${o.steps} | ${o.executed} | ${o.succeeded} |`),
		'',
	];
	writeFileSync(resolve(dir, 'README.md'), lines.join('\n'));
	console.log(`\n${outcomes.length} workflows; ${succeeded}/${total} steps succeeded`);
}

main().catch((error) => {
	console.error(error);
	process.exit(1);
});
