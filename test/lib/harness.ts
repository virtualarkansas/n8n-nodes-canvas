import { randomUUID } from 'node:crypto';
import { appendFileSync, mkdirSync } from 'node:fs';
import { resolve } from 'node:path';
import { CANVAS_NODE_TYPE, N8nClient } from './n8n';
import type { ExecutionResult, Json, N8nNode, N8nWorkflow } from './n8n';
import { loadState, workerPool } from './state';

export interface RunNodeOptions {
	resource: string;
	operation: string;
	/** Node parameters other than resource/operation/authentication. */
	params?: Json;
	/** Input items (json). Defaults to a single empty item. */
	items?: Json[];
	/** Input items that carry a binary property (file uploads, imports); used instead of `items`. */
	binary?: BinaryInput[];
	/** Which seeded persona's credential to use. Default: admin. */
	persona?: string;
	/** 'accessToken' (default), 'oAuth2' or 'ltiAdvantage'; follows the type of `credential` when that is given. */
	authentication?: 'accessToken' | 'oAuth2' | 'ltiAdvantage';
	/** Use this n8n credential instead of the persona's (for credentials a test creates itself). */
	credential?: { id: string; name: string; type: string };
	/** Node-level settings from the n8n node settings tab. */
	nodeSettings?: Pick<N8nNode, 'onError' | 'continueOnFail' | 'retryOnFail' | 'alwaysOutputData'>;
	/** Keep the workflow in n8n after the run (for debugging in the editor). */
	keep?: boolean;
}

/** One input item with a file in a binary property. */
export interface BinaryInput {
	/** File name of the binary property (omit to test files without a name). */
	fileName?: string;
	mimeType?: string;
	/** Exact content as base64, or ... */
	b64?: string;
	/** ... a size in bytes: the content is generated by `patternBuffer(size)`. */
	size?: number;
	/** Name of the binary property. Default: data. */
	property?: string;
	/** JSON of the item. */
	json?: Json;
}

/** Deterministic content for generated files, so uploads can be compared byte for byte. */
export function patternBuffer(size: number): Buffer {
	const buffer = Buffer.alloc(size);
	for (let i = 0; i < size; i++) {
		buffer[i] = (i * 31 + (i >> 8) * 7) & 0xff;
	}
	return buffer;
}

/** Code node that turns the webhook's description of each file into an item with a binary property. */
const TO_BINARY_CODE = `
const out = [];
for (let index = 0; index < items.length; index++) {
	const input = items[index].json;
	const item = { json: input.json ?? {}, pairedItem: { item: index } };
	if (input.b64 !== undefined || input.size !== undefined) {
		let buffer;
		if (input.b64 !== undefined) {
			buffer = Buffer.from(input.b64, 'base64');
		} else {
			buffer = Buffer.alloc(input.size);
			for (let i = 0; i < input.size; i++) buffer[i] = (i * 31 + (i >> 8) * 7) & 0xff;
		}
		const binary = { data: buffer.toString('base64'), mimeType: input.mimeType ?? 'application/octet-stream' };
		if (input.fileName !== undefined) binary.fileName = input.fileName;
		item.binary = { [input.property ?? 'data']: binary };
	}
	out.push(item);
}
return out;
`;

export interface RunNodeResult {
	/** True when the whole execution finished without a workflow error. */
	ok: boolean;
	/** Items on the Success output (json). */
	success: Json[];
	/** Items on the Error output (json). */
	error: Json[];
	/** Items on the Debug output (json), when debug mode is on. */
	debug: Json[];
	/** Raw success items including pairedItem. */
	rawSuccess: Array<{ json: Json; pairedItem?: unknown; binary?: Json }>;
	/** Node/workflow level failure, when the node threw. */
	failure?: { message: string; description?: string; httpCode?: string; raw: Json };
	execution: ExecutionResult;
	webhookStatus: number;
}

const NODE_NAME = 'Canvas';

/**
 * Every node execution is logged so the coverage report can show, per operation,
 * whether the battery really ran it against Canvas and how it ended.
 */
const RESULTS_DIR = resolve(__dirname, '..', '.results');
const OPS_LOG = resolve(RESULTS_DIR, 'ops.jsonl');

export interface OpRecord {
	resource: string;
	operation: string;
	outcome: 'success' | 'error-output' | 'failed' | 'debug' | 'skipped';
	/** Why an operation cannot be exercised on the local instance (outcome = skipped). */
	reason?: string;
	at: string;
}

function logOp(record: Omit<OpRecord, 'at'>): void {
	mkdirSync(RESULTS_DIR, { recursive: true });
	appendFileSync(OPS_LOG, JSON.stringify({ ...record, at: new Date().toISOString() }) + '\n');
}

/** Name of the running vitest test, when the harness is used from a test. */
async function currentTest(): Promise<{ file?: string; name?: string }> {
	try {
		// vitest is ESM-only; the harness is also used from plain scripts, hence the dynamic import.
		const { expect } = await import('vitest');
		const state = expect.getState();
		return { file: state.testPath, name: state.currentTestName };
	} catch {
		return {};
	}
}

/**
 * Successful runs are recorded with their parameters so importable example
 * workflows can be generated from exactly what the battery executed
 * (see test/tools/export-workflows.ts).
 */
const RUNS_LOG = resolve(RESULTS_DIR, 'runs.jsonl');

async function logRun(opts: RunNodeOptions, outcome: OpRecord['outcome'], success: Json[]): Promise<void> {
	const ids: Json[] = success.slice(0, 3).map((item) => {
		const picked: Json = {};
		for (const [key, value] of Object.entries(item)) {
			if ((typeof value === 'string' || typeof value === 'number') && /(^|_)(id|url|uuid|key)$/i.test(key)) {
				picked[key] = value;
			}
		}
		return picked;
	});
	mkdirSync(RESULTS_DIR, { recursive: true });
	appendFileSync(
		RUNS_LOG,
		JSON.stringify({
			session: process.env.BATTERY_SESSION ?? '0',
			...(await currentTest()),
			resource: opts.resource,
			operation: opts.operation,
			persona: opts.credential ? 'custom' : (opts.persona ?? 'admin'),
			params: opts.params ?? {},
			items: opts.items,
			outcome,
			outputCount: success.length,
			outputIds: ids,
			at: new Date().toISOString(),
		}) + '\n',
	);
}

/**
 * Declare that an operation is not executed against the local Canvas, and why
 * (for example: it is served by a hosted Instructure service). It still has to
 * pass the route audit in the unit tests.
 */
export function skipOp(resource: string, operation: string, reason: string): void {
	logOp({ resource, operation, outcome: 'skipped', reason });
}

let client: N8nClient | undefined;
export function n8n(): N8nClient {
	client ??= new N8nClient();
	return client;
}

export function canvasNode(opts: RunNodeOptions, name = NODE_NAME, position: [number, number] = [440, 0]): N8nNode {
	const state = loadState();
	const persona = opts.persona ?? 'admin';
	const credKey = opts.authentication === 'oAuth2' ? `${persona}OAuth2` : persona;
	const cred = opts.credential ?? workerPool(state)?.credentials[credKey] ?? state.n8n.credentials[credKey];
	if (!cred) {
		throw new Error(`No n8n credential for persona "${credKey}" in test state`);
	}
	const byType: Record<string, RunNodeOptions['authentication']> = {
		canvasOAuth2Api: 'oAuth2',
		canvasLtiAdvantageApi: 'ltiAdvantage',
	};
	const authentication = opts.authentication ?? byType[cred.type] ?? 'accessToken';
	return {
		id: randomUUID(),
		name,
		type: CANVAS_NODE_TYPE,
		typeVersion: 1,
		position,
		parameters: {
			authentication,
			resource: opts.resource,
			operation: opts.operation,
			...(opts.params ?? {}),
		},
		credentials: { [cred.type]: { id: cred.id, name: cred.name } },
		...(opts.nodeSettings ?? {}),
	};
}

/**
 * Wrap a Canvas node in the smallest workflow that lets the battery drive it:
 * Webhook (POST, wait for last node) -> Split Out body.items -> Canvas.
 */
export function wrapInWebhookWorkflow(
	node: N8nNode,
	label: string,
	withBinary = false,
): { workflow: N8nWorkflow; path: string } {
	const path = `canvas-battery-${randomUUID()}`;
	const toBinary: N8nNode = {
		id: randomUUID(),
		name: 'To Binary',
		type: 'n8n-nodes-base.code',
		typeVersion: 2,
		position: [330, 160],
		parameters: { mode: 'runOnceForAllItems', language: 'javaScript', jsCode: TO_BINARY_CODE },
	};
	const workflow: N8nWorkflow = {
		name: `[battery] ${label}`,
		settings: { executionOrder: 'v1' },
		nodes: [
			{
				id: randomUUID(),
				name: 'Webhook',
				type: 'n8n-nodes-base.webhook',
				typeVersion: 2,
				position: [0, 0],
				webhookId: path,
				parameters: { httpMethod: 'POST', path, responseMode: 'lastNode', options: {} },
			},
			{
				id: randomUUID(),
				name: 'Items',
				type: 'n8n-nodes-base.splitOut',
				typeVersion: 1,
				position: [220, 0],
				parameters: { fieldToSplitOut: 'body.items', options: {} },
			},
			...(withBinary ? [toBinary] : []),
			node,
		],
		connections: {
			Webhook: { main: [[{ node: 'Items', type: 'main', index: 0 }]] },
			Items: { main: [[{ node: withBinary ? toBinary.name : node.name, type: 'main', index: 0 }]] },
			...(withBinary ? { [toBinary.name]: { main: [[{ node: node.name, type: 'main', index: 0 }]] } } : {}),
		},
	};
	return { workflow, path };
}

/** Execute one Canvas node operation on the real n8n instance and collect its outputs. */
const QUOTA_EXHAUSTED = /rate limit quota is still below the threshold/i;

/** Did the node give up on the quota before it sent anything for any item? */
function blockedByQuota(result: RunNodeResult): boolean {
	if (result.success.length > 0 || result.debug.length > 0) return false;
	const texts = [result.failure?.message ?? '', ...result.error.map((e) => String(e.errorMessage ?? ''))].filter(
		(text) => text !== '',
	);
	return texts.length > 0 && texts.every((text) => QUOTA_EXHAUSTED.test(text));
}

/**
 * Run one Canvas node on the battery's n8n instance.
 *
 * Canvas throttles per token and other test files may be using the same persona.
 * When the node's pre-flight check gives up on the quota before sending anything,
 * that says nothing about the operation under test, so the run is repeated once the
 * quota had time to recover (nothing reached Canvas, so nothing is done twice).
 * Tests that set their own `rateLimiting` options are testing exactly that and are
 * never repeated.
 *
 * On a heavily shared Canvas, BATTERY_RATE_LIMIT_THRESHOLD=<n> makes every run that
 * does not set its own rate limiting use that pre-flight threshold instead of 300.
 */
export async function runNode(opts: RunNodeOptions): Promise<RunNodeResult> {
	const ownRateLimiting = (opts.params as Json | undefined)?.rateLimiting !== undefined;
	const threshold = process.env.BATTERY_RATE_LIMIT_THRESHOLD;
	if (!ownRateLimiting && threshold) {
		opts = { ...opts, params: { ...(opts.params ?? {}), rateLimiting: { threshold: Number(threshold) } } };
	}
	for (let attempt = 0; ; attempt++) {
		const result = await runNodeOnce(opts);
		if (ownRateLimiting || attempt >= 4 || !blockedByQuota(result)) return result;
		await new Promise((resolve) => setTimeout(resolve, 15_000));
	}
}

async function runNodeOnce(opts: RunNodeOptions): Promise<RunNodeResult> {
	const api = n8n();
	const node = canvasNode(opts);
	const { workflow, path } = wrapInWebhookWorkflow(node, `${opts.resource}.${opts.operation}`, opts.binary !== undefined);
	const workflowId = await api.createWorkflow(workflow);
	try {
		await api.activate(workflowId);
		const items = opts.binary ?? opts.items ?? [{ _item: 0 }];
		const hook = await api.callWebhook(path, { items });
		// Runs with files can take a while (large uploads).
		const execution = await api.lastExecution(workflowId, opts.binary ? 400 : undefined);
		const run = execution.nodes[NODE_NAME]?.[0];
		const nodeError =
			run?.error ??
			execution.error ??
			Object.values(execution.nodes)
				.flatMap((runs) => runs.map((r) => r.error))
				.find(Boolean);
		const debugMode = (opts.params as Json | undefined)?.debugMode === true;
		const outcome: OpRecord['outcome'] =
			execution.status !== 'success'
				? 'failed'
				: debugMode
					? 'debug'
					: (run?.outputs[1]?.length ?? 0) > 0
						? 'error-output'
						: 'success';
		logOp({ resource: opts.resource, operation: opts.operation, outcome });
		// A run with both successful and failed items counts as a success for coverage too.
		if (outcome === 'error-output' && (run?.outputs[0]?.length ?? 0) > 0) {
			logOp({ resource: opts.resource, operation: opts.operation, outcome: 'success' });
		}
		await logRun(opts, outcome, run?.outputs[0] ?? []);
		return {
			ok: execution.status === 'success',
			success: run?.outputs[0] ?? [],
			error: run?.outputs[1] ?? [],
			debug: run?.outputs[2] ?? [],
			rawSuccess: run?.rawOutputs[0] ?? [],
			failure: nodeError
				? {
						message: String(nodeError.message ?? ''),
						description: nodeError.description as string | undefined,
						httpCode: nodeError.httpCode as string | undefined,
						raw: nodeError,
					}
				: undefined,
			execution,
			webhookStatus: hook.status,
		};
	} finally {
		if (!opts.keep) {
			await api.deleteWorkflow(workflowId).catch(() => undefined);
		}
	}
}

/** Run and require success; returns the Success output items. Throws with full context otherwise. */
export async function runOk(opts: RunNodeOptions): Promise<Json[]> {
	const result = await runNode(opts);
	if (!result.ok || result.error.length > 0) {
		throw new Error(
			`${opts.resource}.${opts.operation} failed: ` +
				JSON.stringify(result.failure ?? result.error, null, 2).slice(0, 2000) +
				`\nparams: ${JSON.stringify(opts.params ?? {})}`,
		);
	}
	return result.success;
}

/**
 * Create an n8n Canvas API credential for a token the test obtained itself;
 * pass the result as `credential` to runNode/runOk.
 */
export async function createCredential(
	token: string,
	label = 'test-created',
	canvasUrl = loadState().canvas.url,
): Promise<{ id: string; name: string; type: string }> {
	const name = `Canvas battery (${label} ${randomUUID().slice(0, 8)})`;
	const created = await n8n().api<{ id: string }>('POST', '/credentials', {
		name,
		type: 'canvasApi',
		data: { canvasUrl, accessToken: token, allowedHttpRequestDomains: 'all' },
	});
	return { id: String(created.id), name, type: 'canvasApi' };
}
